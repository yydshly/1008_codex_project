  check('阅读页桌面无水平溢出',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.goto(base+'overview/',{waitUntil:'networkidle'});await page.locator('#overview-image').evaluate(i=>i.decode());
  await page.screenshot({path:path.join(project,'assets/understanding/viewer-desktop.jpg'),type:'jpeg',quality:92});
  const mobile=await context.newPage();observe(mobile);await mobile.setViewportSize({width:390,height:844});
  await mobile.goto(base+'#understanding',{waitUntil:'networkidle'});
  check('手机首页总览入口正常',await mobile.locator('.understanding-actions .primary-link').isVisible());
  check('手机首页无水平溢出',await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.screenshot({path:path.join(project,'assets/understanding/mobile.jpg'),type:'jpeg',quality:92});
  await mobile.locator('.understanding-actions .primary-link').click();
  await mobile.locator('#overview-image').evaluate(i=>i.decode());
  check('手机阅读页无水平溢出',await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.locator('#zoom-in').click();
