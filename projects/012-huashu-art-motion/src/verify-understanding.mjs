  check('400%放大边界与按钮状态',await page.locator('#zoom-value').textContent()==='400%'&&await page.locator('#zoom-in').isDisabled());
  await page.locator('#zoom-reset').click();
  check('适应宽度恢复图像和滚动位置',await page.locator('#zoom-value').textContent()==='100%'&&await page.locator('#overview-viewport').evaluate(e=>e.scrollWidth===e.clientWidth));
  const pendingDownload=page.waitForEvent('download');
  await page.locator('.overview-toolbar a[download]').click();
  const download=await pendingDownload,downloaded=await readFile(await download.path());
  check('下载真实完整PNG而非HTML',download.suggestedFilename().endsWith('.png')&&createHash('sha256').update(downloaded).digest('hex')===digest);
  await download.delete();
