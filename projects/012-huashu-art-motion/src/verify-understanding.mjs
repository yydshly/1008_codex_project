  await details.nth(1).locator('summary').click();
  check('完整能力解释可展开且有源码依据',await details.nth(1).getAttribute('open')!==null&&await details.nth(1).locator('article').count()===9&&await details.nth(1).locator('article a').count()===9);
  await details.nth(4).locator('summary').click();
  check('价值判断标明同模型对比与待验证范围',(await details.nth(4).textContent()).includes('尚未完成同任务、同模型'));
  check('来源固定到研究提交',await page.locator('.overview-sources>a').count()===10&&await page.locator('.overview-sources>a').evaluateAll(a=>a.every(e=>e.href.includes('/blob/57d67608ab458f57d9b153b1a2831b921e22498b/'))));
  const refs=await page.evaluate(()=>[...new Set([...document.querySelectorAll('[src],link[href],a[href]')].map(e=>e.getAttribute('src')||e.getAttribute('href')).filter(s=>s?.startsWith('./')||s?.startsWith('../')))]);
