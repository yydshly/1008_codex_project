  check('原有35种风格与9种语法完整',await page.locator('.style-card').count()===35&&await page.locator('.grammar').count()===9);
  await page.goto(base+'#style=33_rubberhose',{waitUntil:'networkidle'});
  await page.waitForSelector('.player-stage.ready',{timeout:120000});
  check('橡皮管深链接与原版引擎可用',(await page.locator('#exhibit-title').textContent()).includes('橡皮管')&&await page.frames().find(f=>f.url().includes('/engine/index.html')).evaluate(()=>Boolean(window.__canvas&&window.__ready)));
  await page.locator('.topbar nav a[href="#understanding"]').click();
  check('从风格展示可回顾理解',page.url().endsWith('#understanding'));
  await page.locator('.understanding-actions .primary-link').click();
  await page.locator('#overview-image').evaluate(i=>i.decode());
  check('高清阅读页可从首页进入',page.url()===base+'overview/');
  await page.reload({waitUntil:'networkidle'});
  check('阅读页直接刷新正常',await page.locator('h1').textContent()==='Huashu 艺术动画能力与价值总览');
  const png=await context.request.get(base+'assets/understanding/overview.png');
  const bytes=await png.body(),digest=createHash('sha256').update(bytes).digest('hex');
  const manifest=JSON.parse(await readFile(path.join(project,'assets/understanding/manifest.json'),'utf8'));
  check('生产路径高清PNG内容类型与字节一致',png.ok()&&png.headers()['content-type']==='image/png'&&digest===manifest.output.sha256);
  check('PNG真实尺寸为3200×8524',bytes.readUInt32BE(16)===3200&&bytes.readUInt32BE(20)===8524);
  check('初始适应宽度可完整浏览',await page.locator('#zoom-value').textContent()==='100%'&&await page.locator('#zoom-out').isDisabled());
  await page.locator('#zoom-in').click();
  await page.waitForFunction(()=>document.querySelector('#overview-image').clientWidth>document.querySelector('#overview-viewport').clientWidth);
  check('放大改变图像宽度并允许横向查看',await page.locator('#zoom-value').textContent()==='150%'&&await page.locator('#overview-viewport').evaluate(e=>e.scrollWidth>e.clientWidth));
  await page.locator('#overview-viewport').focus();await page.keyboard.press('+');
