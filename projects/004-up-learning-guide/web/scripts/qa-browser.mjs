// 实际浏览器流程验证。可通过环境中已有的 Playwright 模块运行，无站点运行时依赖。
import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const modulePath=process.argv[2];
if(!modulePath)throw new Error('用法：node scripts/qa-browser.mjs <Playwright package.json绝对路径>');
const {chromium}=createRequire(modulePath)('playwright');
const base=process.env.UP_PREVIEW_URL || 'http://127.0.0.1:4194/1008_codex_project/004-up-learning-guide/';
const project=path.resolve(fileURLToPath(new URL('../../',import.meta.url)));
const browser=await chromium.launch({headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
page.on('pageerror',error=>errors.push(error.message));
const go=async(route='overview')=>{await page.goto(base+'#/'+route);await page.locator('main h1').waitFor();};
try{
  await go();
  assert((await page.locator('main h1').innerText()).includes('知识地图'));
  await page.getByRole('tab',{name:'保持迁移'}).click();
  assert((await page.locator('#method-panel').innerText()).includes('撤掉提示'));
  await page.getByRole('tab',{name:'定义任务'}).click();
  await page.screenshot({path:path.join(project,'assets/cover.png'),fullPage:false});
  await go('guide/02-english');
  assert((await page.locator('.prose').innerText()).includes('CEFR'));
  assert((await page.locator('.prose h2').count())>=8);
  const tableRegion=page.locator('.table-wrap').first();
  assert(await tableRegion.count());
  await go('catalog');
  assert.equal(await page.locator('.catalog-card').count(),97);
  await page.locator('#catalog-query').fill('语法');
  assert((await page.locator('.catalog-card').count())>0 && (await page.locator('.catalog-card').count())<97);
  await page.locator('#catalog-query').fill('不存在的内容abcdef');
  assert.equal(await page.locator('.empty-state').count(),1);
  await go('worksheets');
  assert.equal(await page.locator('.worksheet-card').count(),25);
  await page.getByRole('button',{name:'生活与恢复',exact:true}).click();
  assert.equal(await page.locator('.worksheet-card').count(),1);
  await page.getByRole('link',{name:'查看填写说明',exact:true}).click();
  await page.waitForURL(/guide\/05-templates\?section=/);
  assert((await page.locator('.prose').innerText()).includes('生活进阶工作表'));
  await go('words');
  assert.equal(await page.locator('.word-item').count(),392);
  await page.locator('#words-query').fill('context');
  assert((await page.locator('.word-item').count())>0 && (await page.locator('.word-item').count())<392);
  await go('resources');
  assert.equal(await page.locator('.resource-row').count(),67);
  await page.locator('#resources-domain').selectOption('api.crossref.org');
  assert((await page.locator('.resource-row').count())>0 && (await page.locator('.resource-row').count())<67);
  await page.keyboard.press('/');
  await page.locator('#search-input').fill('跨会话');
  assert((await page.locator('.search-result').count())>0);
  await page.locator('.search-result').first().click();
  assert(!(await page.locator('#search-dialog').evaluate(element=>element.open)));
  for(const route of ['topics','guide/01-learning-system','guide/03-ai-and-projects','guide/04-life-and-long-term','guide/06-publishing','guide/07-glossary-and-resources','guide/sources'])await go(route);
  await page.reload();await page.locator('.prose').waitFor();
  const response=await page.request.get(base+'research/guides/02-english.md');
  assert.equal(response.status(),200);
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(base);await mobile.locator('main h1').waitFor();
  assert(await mobile.locator('#sidebar').evaluate(element=>element.inert));
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.screenshot({path:path.join(project,'assets/mobile.png'),fullPage:true});
  await mobile.getByRole('button',{name:'打开导航',exact:true}).click();
  await mobile.locator('[data-nav="words"]').click();
  await mobile.locator('#words-query').waitFor();
  assert.equal(await mobile.locator('.word-item').count(),392);
  assert(!(await mobile.locator('#sidebar').getAttribute('class')).includes('open'));
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.goto(base+'#/guide/02-english');await mobile.locator('.prose').waitFor();
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.locator('.mobile-toc summary').click();
  await mobile.locator('.mobile-toc a').nth(1).click();
  await mobile.reload();await mobile.locator('.prose').waitFor();
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.close();
  await page.setViewportSize({width:1280,height:900});
  await go();
  await page.evaluate(()=>{
    const sizes=[...document.querySelectorAll('body *')].map(element=>[element,parseFloat(getComputedStyle(element).fontSize)]);
    for(const [element,size] of sizes)if(Number.isFinite(size))element.style.fontSize=`${size*2}px`;
  });
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'放大文字时不得溢出整个页面');
  assert.deepEqual(errors,[],'浏览器不应出现运行错误');
  console.log('浏览器验证通过：完整路由、正文、六步切换、目录/工作纸/词表/资源筛选、空结果、全文搜索、下载、深链接刷新、390px手机导航与正文、200%文字放大。');
}finally{await browser.close();}
