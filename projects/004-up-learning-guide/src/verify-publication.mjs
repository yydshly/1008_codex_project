// 本研究的发布核验：静态正文、资料覆盖、原图与真实浏览器流程。
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const project=path.resolve(fileURLToPath(new URL('../',import.meta.url)));
const base=process.argv[2];
const playwrightPath=process.argv[3];
if(!base?.endsWith('/')||!playwrightPath)throw new Error('用法：node src/verify-publication.mjs <以/结尾的站点URL> <Playwright包package.json绝对路径> [记录名称]');
const name=process.argv[4]||'local';
if(!/^[a-z-]+$/.test(name))throw new Error('记录名称须为小写英文与短横线');
const require=createRequire(playwrightPath);
const {chromium}=require('playwright');
const manifest=JSON.parse(await fs.readFile(path.join(project,'sources/guide-manifest.json'),'utf8'));
const output=path.join(project,'assets/publication');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const result={base,verifiedAt:new Date().toISOString(),guide:manifest,checks:{},errors:[]};
try{
 const context=await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true});
 const page=await context.newPage();
 page.on('pageerror',error=>result.errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')result.errors.push(message.text())});
 page.on('response',response=>{if(response.status()>=400)result.errors.push(response.status()+' '+response.url())});
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('.understanding-summary dd').first().waitFor();
 assert.equal(await page.locator('.understanding-summary dt').count(),11);
 const image=page.locator('.understanding .core-map img');
 await image.evaluate(node=>node.decode());
 assert.deepEqual(await image.evaluate(node=>[node.naturalWidth,node.naturalHeight]),[2400,1600]);
 await page.screenshot({path:path.join(output,name+'-desktop.png')});
 result.checks.summaryItems=11;
 const dataResponse=await context.request.get(new URL('data/content.json',base).href);
 assert.equal(dataResponse.status(),200);
 const data=await dataResponse.json();
 assert.equal(data.guides.length,8);assert.equal(data.pages.length,97);assert.equal(data.worksheets.length,25);assert.equal(data.wordLists.flatMap(item=>item.terms).length,392);assert.equal(data.resources.length,67);
 result.checks.coverage={guides:7,sourcePage:1,pages:97,worksheets:25,wordEntries:392,resources:67};
 const pngResponse=await context.request.get(new URL('research/assets/up-core-map.png',base).href);
 assert.equal(pngResponse.status(),200);assert(pngResponse.headers()['content-type'].includes('image/png'));
 const png=await pngResponse.body();
 assert.equal(createHash('sha256').update(png).digest('hex'),manifest.sha256);
 result.checks.guideBytesPreserved=true;
 const links=['research/UNDERSTANDING.md','research/assets/up-core-map.svg','research/assets/up-core-map-prompt.md','research/sources/guide-manifest.json','research/licenses/LICENSE.md','research/licenses/LICENSE-CONTENT.md','research/licenses/LICENSE-CODE.md',...data.guides.map(item=>'research/'+item.file)];
 for(const link of links){const response=await context.request.get(new URL(link,base).href);assert.equal(response.status(),200,link)}
 result.checks.downloads=links.length;
 await page.locator('.understanding-detail summary').click();
 assert(await page.locator('.understanding-detail').evaluate(node=>node.open));
 assert.equal(await page.locator('.understanding-detail h2').count(),10);
 await page.getByRole('button',{name:'搜索全部内容'}).click();
 await page.locator('#search-input').fill('私有学习工作台');
 await page.locator('#search-results a').first().click();
 assert(await page.locator('.understanding-detail').evaluate(node=>node.open));
 assert(page.url().includes('#/overview?section=understanding-'));
 await page.reload({waitUntil:'networkidle'});
 assert(await page.locator('.understanding-detail').evaluate(node=>node.open));
 result.checks.searchAndDeepRefresh=true;
 await page.goto(base+'#/overview');await page.locator('#step-4').click();
 assert.equal(await page.locator('#step-4').getAttribute('aria-selected'),'true');
 result.checks.methodTabs=true;
 await page.goto(base+'#/catalog');await page.locator('#catalog-count').waitFor();assert((await page.locator('#catalog-count').innerText()).includes('97'));
 await page.goto(base+'#/worksheets');await page.locator('#tools-count').waitFor();assert((await page.locator('#tools-count').innerText()).includes('25'));
 await page.goto(base+'#/map');await page.locator('.core-map img').evaluate(node=>node.decode());
 const downloadEvent=page.waitForEvent('download');await page.getByRole('link',{name:'保存原图',exact:true}).click();
 const download=await downloadEvent;
 assert.equal(download.suggestedFilename(),'up-core-map.png');
 assert.equal(createHash('sha256').update(await fs.readFile(await download.path())).digest('hex'),manifest.sha256);
 result.checks.actualDownload=true;
 const popupEvent=page.waitForEvent('popup');await page.getByRole('link',{name:'打开原图，放大阅读',exact:true}).click();
 const popup=await popupEvent;await popup.waitForLoadState();assert(popup.url().endsWith('up-core-map.png'));await popup.close();
 result.checks.originalPopup=true;
 result.checks.mobile=[];
 for(const width of [390,320]){
  await page.setViewportSize({width,height:844});await page.goto(base+'#/overview');await page.locator('.understanding-summary').waitFor();
  await page.locator('.understanding-detail summary').click();
  const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(dimensions.scroll<=dimensions.width,JSON.stringify(dimensions));
  await page.getByRole('button',{name:'打开导航',exact:true}).click();await page.locator('[data-nav="overview"]').click();
  assert(!(await page.locator('#sidebar').evaluate(node=>node.classList.contains('open'))));
  if(width===390){await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));await page.screenshot({path:path.join(output,name+'-mobile.png'),animations:'disabled'});}
  result.checks.mobile.push(dimensions);
 }
 const noScript=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const staticPage=await noScript.newPage();
 await staticPage.goto(base);
 assert.equal(await staticPage.locator('.understanding-summary dt').count(),11);
 await staticPage.locator('.understanding-detail summary').click();
 assert.equal(await staticPage.locator('.understanding-detail h2').count(),10);
 const staticWidth=await staticPage.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert(staticWidth.scroll<=staticWidth.width);
 assert.equal(await staticPage.locator('noscript a').count(),8);
 result.checks.noJavaScript=true;
 assert.deepEqual(result.errors,[]);
 result.passed=true;
 await fs.writeFile(path.join(project,'src',name+'-publication-verification.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result,null,2));
}finally{await browser.close()}

