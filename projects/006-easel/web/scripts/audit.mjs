// 验证真实发布契约：全文覆盖、固定原图、索引一致、静态阅读与资源引用。
import {readFile,access} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const argv=process.argv.slice(2),position=argv.indexOf('--dir');
const out=position<0?path.join(root,'dist'):path.resolve(argv[position+1]);
const load=async file=>JSON.parse(await readFile(path.join(out,file),'utf8'));
const [pub,facts,caps]=await Promise.all(['publication.json','facts.json','capabilities.json'].map(load));
const html=await readFile(path.join(out,'index.html'),'utf8');
const image=await readFile(path.join(out,'capability-map.png'));
assert.equal(pub.meta.commit,facts.commit);assert.equal(caps.commit,facts.commit);
assert.equal(caps.items.length,114);assert.equal(new Set(caps.items.map(x=>x.id)).size,114);
assert.equal(createHash('sha256').update(image).digest('hex'),pub.meta.guide.sha256);
assert.ok(image.equals(await readFile(path.join(root,'../assets/capability-map.png'))),'发布图必须保留原始PNG字节');
assert.equal(pub.summaryItems.length,12);assert.equal(pub.overviewItems.length,6);
assert.equal((html.match(/data-summary-item/g)||[]).length,12);
assert.equal((html.match(/data-flow-step/g)||[]).length,7);
assert.equal((html.match(/data-system-module/g)||[]).length,8);
assert.equal((html.match(/data-scenario/g)||[]).length,6);
assert.equal((html.match(/data-personal-value/g)||[]).length,4);
assert.equal((html.match(/data-reuse-route/g)||[]).length,4);
assert.equal((html.match(/data-extension/g)||[]).length,8);
assert.ok(html.indexOf('data-publication-introduction')<html.indexOf('<figure'),'图前需要独立完整介绍');
assert.ok(html.includes('<noscript>'),'无脚本需要说明静态阅读与交互范围');
assert.ok(!html.includes('localhost')&&!html.includes('127.0.0.1'),'公开HTML不应带本机入口');
assert.ok(pub.extensions.every(x=>x.status==='研究建议'));
const catalog=JSON.parse(await readFile(path.resolve(root,'../../../projects.json'),'utf8'));
const project=catalog.projects.find(x=>x.id==='006');
for(const field of ['summary','summaryItems','overviewItems'])assert.deepEqual(pub[field],project[field],`索引与发布资料${field}不一致`);
for(const asset of ['app.js','research-view.mjs','style.css','publication.css','favicon.svg','facts.json','capabilities.json','verification.json','browser-checks.json','research.md','LICENSE.upstream.txt','capability-map-prompt.md'])await access(path.join(out,asset));
for(const match of html.matchAll(/(?:src|href)="(\.\/[^"#]+)"/g))await access(path.resolve(out,match[1].split('?')[0]));
const info=await load('build-info.json');assert.match(info.resourceVersion,/^[0-9a-f]{16}$/);
assert.ok(html.includes(`./publication.css?v=${info.resourceVersion}`)&&html.includes(`./app.js?v=${info.resourceVersion}`),'运行资源应随内容版本更新');
const app=await readFile(path.join(out,'app.js'),'utf8');assert.ok(app.includes(`./research-view.mjs?v=${info.resourceVersion}`)&&app.includes(`const resourceVersion = '${info.resourceVersion}';`));
console.log('Easel发布审计通过：12项摘要、6段图前介绍、7环节、8模块、114技能、6场景、4价值、4复用、8扩展，原图与资源完整。');
