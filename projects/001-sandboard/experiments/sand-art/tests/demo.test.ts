import { expect, test } from 'vitest'
import { Buffer } from 'node:buffer'
import { AirborneSand } from '../src/airborne'
import { createSandDemo, DEMO_DURATION_TICKS, demoPhaseAt } from '../src/demo'
import { FIXED_STEP } from '../src/model'
import { HAND_CAPACITY, HANDFUL_AMOUNT, POUR_RATE } from '../src/hand'
import { exportRecording, importRecording, validateRecording } from '../src/recording'

test('the demo starts from empty glass and advances through real hand gestures without image snapshots', () => {
  const demo = validateRecording(createSandDemo())
  expect(demo.ticks).toBe(DEMO_DURATION_TICKS)
  expect(demo.ticks * FIXED_STEP).toBe(20)
  expect(demo.initial.mode).toBe('lightbox')
  expect([demo.initial.width, demo.initial.height]).toEqual([512, 384])
  expect(new Float32Array(demo.initial.state).every(value => value === 0)).toBe(true)
  expect(new Float32Array(demo.initial.referenceState!).every(value => value === 0)).toBe(true)
  expect(demo.events.every(event => event.type === 'step')).toBe(true)
  const contacts = demo.events.flatMap(event => event.type === 'step' ? [...event.step.contacts] : [])
  expect(new Set(contacts.map(contact => contact.tool))).toEqual(new Set(['pour', 'palm', 'scrape']))
  expect(new Set(contacts.flatMap(contact => contact.pour ? [contact.pour.style] : []))).toEqual(new Set(['scatter', 'handful', 'stream']))
  expect(contacts.filter(contact => contact.pour).every(contact => contact.pour!.natural === true && Number.isFinite(contact.pour!.flow))).toBe(true)
  const tail = demo.events.at(-1)!
  expect(tail.type).toBe('step')
  if (tail.type === 'step') { expect(tail.step.contacts).toEqual([]); expect(tail.repeat).toBeGreaterThanOrEqual(408) }
})

test('phase cues follow the timeline, show the actual hand budget and disappear during the final hold', () => {
  expect(demoPhaseAt(-1).label).toBe('抓起第一把沙')
  expect(demoPhaseAt(72).label).toContain('左山')
  expect(demoPhaseAt(480).handPercent).toBe(100)
  expect(demoPhaseAt(552).label).toContain('右山')
  expect(demoPhaseAt(972).handPercent).toBe(100)
  expect(demoPhaseAt(1044).cursor?.pour?.style).toBe('handful')
  expect(demoPhaseAt(1104).cursor?.pour?.style).toBe('stream')
  expect(demoPhaseAt(1524).cursor?.tool).toBe('palm')
  expect(demoPhaseAt(1716).cursor?.tool).toBe('scrape')
  expect(demoPhaseAt(DEMO_DURATION_TICKS).cursor).toBeNull()
  expect(demoPhaseAt(Infinity).label).toBe('抓起第一把沙')
  const tick = 200, original = demoPhaseAt(tick)
  const changed = demoPhaseAt(tick)
  changed.cursor!.x = 1
  changed.cursor!.pour!.height = 0
  expect(demoPhaseAt(tick)).toEqual(original)
})

test('all three handfuls obey their finite budget including the recorded natural flow multiplier', () => {
  const demo = createSandDemo()
  let tick = 0, hand = 0, remaining = HAND_CAPACITY
  const totals = [0, 0, 0]
  for (const event of demo.events) if (event.type === 'step') for (let repeat = 0; repeat < event.repeat; repeat++, tick++) {
    if (tick === 480 || tick === 972) { hand++; remaining = HAND_CAPACITY }
    for (const contact of event.step.contacts) if (contact.pour) {
      const amount = contact.pour.style === 'handful' ? HANDFUL_AMOUNT * (contact.pour.burst ?? 0) : POUR_RATE * event.step.dt
      const cost = amount * contact.strength * contact.pressure * (contact.pour.flow ?? 1)
      totals[hand] += cost; remaining -= cost
      expect(remaining).toBeGreaterThanOrEqual(-0.00001)
    }
    expect(demoPhaseAt(tick).handPercent).toBe(Math.round(Math.max(0, remaining) / HAND_CAPACITY * 100))
  }
  expect(totals.every(total => total > 2000 && total <= HAND_CAPACITY + 0.00001)).toBe(true)
  expect(totals.reduce((sum, total) => sum + total, 0)).toBeLessThanOrEqual(HAND_CAPACITY * 3 + 0.00001)
})

test('natural airborne mass is generated by the recorded gestures and fully settles during the hold', () => {
  const air = new AirborneSand(32, 24)
  const demo = createSandDemo()
  let deposited = 0, observedFlying = false
  for (const event of demo.events) if (event.type === 'step') for (let repeat = 0; repeat < event.repeat; repeat++) {
    const field = air.advance(event.step)
    deposited += field.reduce((sum, value) => sum + value, 0)
    observedFlying ||= air.pending
  }
  expect(observedFlying).toBe(true)
  expect(air.pending).toBe(false)
  expect(air.emittedMass).toBeGreaterThan(7000)
  expect(air.emittedMass).toBeLessThanOrEqual(HAND_CAPACITY * 3 + 0.00001)
  expect(Math.abs(deposited - air.emittedMass)).toBeLessThan(0.01)
})

test('demo files round trip all actual natural contacts and each new recording owns its buffers', async () => {
  const demo = createSandDemo()
  const restored = await importRecording(await exportRecording(demo))
  expect(restored.events).toEqual(demo.events)
  expect(restored.title).toBe(demo.title)
  expect(restored.ticks).toBe(DEMO_DURATION_TICKS)
  expect(Buffer.compare(Buffer.from(restored.initial.state), Buffer.from(demo.initial.state))).toBe(0)
  expect(Buffer.compare(Buffer.from(restored.initial.referenceState!), Buffer.from(demo.initial.referenceState!))).toBe(0)
  new Float32Array(demo.initial.state)[0] = 3
  const firstPour = demo.events.find(event => event.type === 'step' && event.step.contacts[0]?.pour)
  if (firstPour?.type === 'step') firstPour.step.contacts[0].pour!.height = 0
  const fresh = createSandDemo()
  expect(new Float32Array(fresh.initial.state)[0]).toBe(0)
  const freshPour = fresh.events.find(event => event.type === 'step' && event.step.contacts[0]?.pour)
  expect(freshPour?.type === 'step' && freshPour.step.contacts[0].pour!.height).toBeGreaterThan(0)
})
